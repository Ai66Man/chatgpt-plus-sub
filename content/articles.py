def table(headers, rows, caption=None):
    head = "".join("<th scope=\"col\">" + h + "</th>" for h in headers)
    body = ""
    for row in rows:
        cells = "<th scope=\"row\">" + row[0] + "</th>"
        cells += "".join("<td>" + c + "</td>" for c in row[1:])
        body += "<tr>" + cells + "</tr>"
    cap = "<caption>" + caption + "</caption>" if caption else ""
    return ("<div class=\"table-wrap\" tabindex=\"0\" role=\"region\" aria-label=\"对比表，可横向滚动\">"
            "<table>" + cap + "<thead><tr>" + head + "</tr></thead><tbody>" + body + "</tbody></table></div>")

